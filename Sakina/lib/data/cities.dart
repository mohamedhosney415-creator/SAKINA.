/// المحافظات المصرية الـ27 والمدن/المراكز الرئيسية.
/// الإحداثيات تقريبية لمركز كل مدينة وتكفي لحساب المواقيت بدقة الدقيقة.
class City {
  final String name;
  final double lat, lng;
  const City(this.name, this.lat, this.lng);
}

class Gov {
  final String name;
  final List<City> cities;
  const Gov(this.name, this.cities);
}

class Cities {
  static List<Gov> get all => _govs;

  static City find(String gov, String city) {
    for (final g in _govs) {
      if (g.name == gov) {
        for (final c in g.cities) {
          if (c.name == city) return c;
        }
        return g.cities.first;
      }
    }
    return _govs.first.cities.first;
  }

  /// بحث بالاسم في المدن والمحافظات. يرجع (محافظة، مدينة).
  static List<MapEntry<Gov, City>> search(String q) {
    final s = _norm(q);
    final out = <MapEntry<Gov, City>>[];
    if (s.isEmpty) return out;
    for (final g in _govs) {
      for (final c in g.cities) {
        if (_norm(c.name).contains(s) || _norm(g.name).contains(s)) {
          out.add(MapEntry(g, c));
        }
      }
    }
    return out;
  }

  static String _norm(String t) => t
      .replaceAll(RegExp('[\u064B-\u065F]'), '')
      .replaceAll('أ', 'ا')
      .replaceAll('إ', 'ا')
      .replaceAll('آ', 'ا')
      .replaceAll('ة', 'ه')
      .replaceAll('ى', 'ي')
      .trim();
}

