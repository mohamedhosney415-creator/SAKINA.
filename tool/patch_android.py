
#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
SAKINA Android project patcher.

Prepares the Android project generated by flutter create:
1. Android permissions and notification/audio/widget components.
2. MainActivity based on AudioServiceActivity.
3. Copies Kotlin widget provider and Android resources.
4. Copies Adhan audio files into res/raw.
5. Configures compileSdk 36.
6. Enables core library desugaring.
"""

import glob
import os
import re
import shutil
import sys

ROOT = os.getcwd()
APP = os.path.join(ROOT, "android", "app")
MAIN = os.path.join(APP, "src", "main")

MARK = "SAKINA_PATCHED"


def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def write(path, content):
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def fail(message):
    print("ERROR:", message)
    sys.exit(1)


# Check Android project
if not os.path.isdir(MAIN):
    fail("android/ غير موجود. شغّل flutter create أولًا.")


# ---------------------------------------------------------
# 1) AndroidManifest.xml
# ---------------------------------------------------------

manifest = os.path.join(MAIN, "AndroidManifest.xml")
xml = read(manifest)

if MARK not in xml:

    permissions = [
        "INTERNET",
        "POST_NOTIFICATIONS",
        "SCHEDULE_EXACT_ALARM",
        "RECEIVE_BOOT_COMPLETED",
        "VIBRATE",
        "WAKE_LOCK",
        "FOREGROUND_SERVICE",
        "FOREGROUND_SERVICE_MEDIA_PLAYBACK",
    ]

    permission_xml = (
        "    <!-- " + MARK + " -->\n"
        + "".join(
            '    <uses-permission android:name="android.permission.'
            + permission
            + '"/>\n'
            for permission in permissions
        )
    )

    if "<application" not in xml:
        fail("لم يتم العثور على application داخل AndroidManifest.xml")

    xml = xml.replace(
        "<application",
        permission_xml + "    <application",
        1
    )

    xml = re.sub(
        r'android:label="[^"]*"',
        'android:label="سكينة"',
        xml,
        count=1
    )

    components = """
        <service
            android:name="com.ryanheise.audioservice.AudioService"
            android:foregroundServiceType="mediaPlayback"
            android:exported="true">
            <intent-filter>
                <action android:name="android.media.browse.MediaBrowserService"/>
            </intent-filter>
        </service>

        <receiver
            android:name="com.ryanheise.audioservice.MediaButtonReceiver"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MEDIA_BUTTON"/>
            </intent-filter>
        </receiver>

        <receiver
            android:exported="false"
            android:name="com.dexterous.flutterlocalnotifications.ScheduledNotificationReceiver"/>

        <receiver
            android:exported="false"
            android:name="com.dexterous.flutterlocalnotifications.ScheduledNotificationBootReceiver">
            <intent-filter>
                <action android:name="android.intent.action.BOOT_COMPLETED"/>
                <action android:name="android.intent.action.MY_PACKAGE_REPLACED"/>
                <action android:name="android.intent.action.QUICKBOOT_POWERON"/>
                <action android:name="com.htc.intent.action.QUICKBOOT_POWERON"/>
            </intent-filter>
        </receiver>

        <receiver
            android:name=".SakinaWidgetProvider"
            android:label="سكينة - المواقيت"
            android:exported="true">
            <intent-filter>
                <action android:name="android.appwidget.action.APPWIDGET_UPDATE"/>
            </intent-filter>
            <meta-data
                android:name="android.appwidget.provider"
                android:resource="@xml/sakina_widget_info"/>
        </receiver>
"""

    if "</application>" not in xml:
        fail("لم يتم العثور على نهاية application في Manifest")

    xml = xml.replace(
        "</application>",
        components + "\n    </application>",
        1
    )

    write(manifest, xml)
    print("Manifest patched")

else:
    print("Manifest already patched")


# ---------------------------------------------------------
# 2) MainActivity + Widget Provider
# ---------------------------------------------------------

kt_files = glob.glob(
    os.path.join(MAIN, "kotlin", "**", "MainActivity.kt"),
    recursive=True
)

if not kt_files:
    fail("MainActivity.kt غير موجود. تأكد من إنشاء مشروع Android بلغة Kotlin.")

main_activity = kt_files[0]
main_content = read(main_activity)

package_match = re.search(
    r"^package\s+([\w.]+)",
    main_content,
    re.MULTILINE
)

if not package_match:
    fail("تعذر استخراج package من MainActivity.kt")

package_name = package_match.group(1)

write(
    main_activity,
    "package " + package_name + "\n\n"
    "import com.ryanheise.audioservice.AudioServiceActivity\n\n"
    "class MainActivity : AudioServiceActivity()\n"
)

provider_source = os.path.join(
    ROOT,
    "android_native",
    "kotlin",
    "SakinaWidgetProvider.kt"
)

if not os.path.isfile(provider_source):
    fail("ملف android_native/kotlin/SakinaWidgetProvider.kt غير موجود")

provider = read(provider_source)

provider = provider.replace("{{PKG}}", package_name)

provider_destination = os.path.join(
    os.path.dirname(main_activity),
    "SakinaWidgetProvider.kt"
)

write(provider_destination, provider)

print("MainActivity and Widget Provider configured")


# ---------------------------------------------------------
# 3) Copy Android Resources
# ---------------------------------------------------------

source_resources = os.path.join(
    ROOT,
    "android_native",
    "res"
)

destination_resources = os.path.join(
    MAIN,
    "res"
)

if not os.path.isdir(source_resources):
    fail("مجلد android_native/res غير موجود")

for directory, _, files in os.walk(source_resources):

    relative = os.path.relpath(
        directory,
        source_resources
    )

    output_directory = os.path.join(
        destination_resources,
        relative
    )

    os.makedirs(output_directory, exist_ok=True)

    for filename in files:

        source_file = os.path.join(
            directory,
            filename
        )

        destination_file = os.path.join(
            output_directory,
            filename
        )

        shutil.copy2(
            source_file,
            destination_file
        )

print("Android resources copied")


# ---------------------------------------------------------
# 4) Copy Adhan Audio to Android res/raw
# ---------------------------------------------------------

raw_directory = os.path.join(
    destination_resources,
    "raw"
)

adhan_directory = os.path.join(
    ROOT,
    "assets",
    "adhan"
)

copied_files = []
seen_names = set()

if os.path.isdir(adhan_directory):

    for filename in sorted(os.listdir(adhan_directory)):

        base, extension = os.path.splitext(filename)

        if extension.lower() not in (
            ".mp3",
            ".ogg",
            ".wav"
        ):
            continue

        if not re.fullmatch(
            r"[a-z][a-z0-9_]*",
            base
        ):
            print(
                "WARNING: اسم ملف الأذان غير صالح لأندرويد:",
                filename
            )
            continue

        if base in seen_names:
            print(
                "WARNING: اسم مكرر تم تجاهله:",
                filename
            )
            continue

        seen_names.add(base)

        os.makedirs(
            raw_directory,
            exist_ok=True
        )

        source_file = os.path.join(
            adhan_directory,
            filename
        )

        destination_file = os.path.join(
            raw_directory,
            base + extension.lower()
        )

        shutil.copy2(
            source_file,
            destination_file
        )

        copied_files.append(filename)

print(
    "Adhan audio files:",
    copied_files if copied_files else "No audio files found"
)


# ---------------------------------------------------------
# 5) Configure Gradle compileSdk 36 + Desugaring
# ---------------------------------------------------------

kotlin_gradle = os.path.join(
    APP,
    "build.gradle.kts"
)

groovy_gradle = os.path.join(
    APP,
    "build.gradle"
)

if os.path.isfile(kotlin_gradle):
    gradle_file = kotlin_gradle
    is_kotlin_dsl = True

elif os.path.isfile(groovy_gradle):
    gradle_file = groovy_gradle
    is_kotlin_dsl = False

else:
    fail("لم أجد build.gradle أو build.gradle.kts داخل android/app")


gradle = read(gradle_file)


# Set compileSdk to 36
compile_sdk_pattern = (
    r"(?m)^([ \t]*)compileSdk(?:Version)?"
    r"[ \t]*(?:=[ \t]*)?.*$"
)

gradle, replacements = re.subn(
    compile_sdk_pattern,
    r"\1compileSdk = 36",
    gradle,
    count=1
)

if replacements == 0:
    fail("تعذر العثور على compileSdk داخل ملف Gradle")


# Enable core library desugaring
if is_kotlin_dsl:

    if "isCoreLibraryDesugaringEnabled" not in gradle:

        gradle, count = re.subn(
            r"(compileOptions\s*\{)",
            r"\1\n        isCoreLibraryDesugaringEnabled = true",
            gradle,
            count=1
        )

        if count == 0:
            fail("تعذر العثور على compileOptions في build.gradle.kts")

    dependency = (
        'coreLibraryDesugaring("com.android.tools:'
        'desugar_jdk_libs:2.1.4")'
    )

    if "coreLibraryDesugaring(" not in gradle:
        gradle += (
            "\n\ndependencies {\n"
            "    " + dependency + "\n"
            "}\n"
        )

else:

    if "coreLibraryDesugaringEnabled" not in gradle:

        gradle, count = re.subn(
            r"(compileOptions\s*\{)",
            r"\1\n        coreLibraryDesugaringEnabled true",
            gradle,
            count=1
        )

        if count == 0:
            fail("تعذر العثور على compileOptions في build.gradle")

    dependency = (
        "coreLibraryDesugaring "
        "'com.android.tools:desugar_jdk_libs:2.1.4'"
    )

    if "coreLibraryDesugaring " not in gradle:
        gradle += (
            "\n\ndependencies {\n"
            "    " + dependency + "\n"
            "}\n"
        )


write(gradle_file, gradle)

print("Gradle compileSdk 36 configured")
print("Core library desugaring configured")


# ---------------------------------------------------------
# DONE
# ---------------------------------------------------------

print("")
print("===================================")
print("SAKINA ANDROID PATCH COMPLETED")
print("compileSdk: 36")
print("Widget resources: copied")
print("Adhan audio: processed")
print("===================================")
